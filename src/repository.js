import { readFileSync, readdirSync, realpathSync } from 'node:fs';
import { dirname, isAbsolute, relative, resolve, sep } from 'node:path';

const binaryProviders = {
  changeset: ['@changesets/cli'],
  playwright: ['@playwright/test'],
  tsc: ['typescript'],
  'tsserver': ['typescript'],
};

export function repository(path) {
  const root = realpathSync(path);
  const manifests = new Map();
  let hoisted;
  const contains = (file) => {
    const name = relative(root, file);
    return name !== '..' && !name.startsWith('..' + sep) && !isAbsolute(name);
  };
  const label = (file) => relative(root, file).split(sep).join('/');
  function read(file) {
    if (!contains(file)) return undefined;
    try {
      const physical = realpathSync(file);
      if (contains(physical)) return readFileSync(physical, 'utf8');
    } catch (error) {
      if (!['ENOENT', 'ENOTDIR', 'EISDIR'].includes(error.code)) {
        throw new Error('Cannot read ' + label(file) + ' (' + error.code + ')');
      }
    }
    return undefined;
  }
  function manifest(directory) {
    if (!manifests.has(directory)) {
      const file = resolve(directory, 'package.json');
      const data = read(file);
      let result;
      if (data !== undefined) {
        try {
          result = { file: label(file), data: JSON.parse(data.replace(/^\uFEFF/, '')) };
        } catch {
          throw new Error(label(file) + ': invalid package.json');
        }
      }
      manifests.set(directory, result);
    }
    return manifests.get(directory);
  }
  function packageChain(directory) {
    const result = [];
    while (directory && contains(directory)) {
      const pkg = manifest(directory);
      if (pkg) result.push(pkg);
      if (directory === root) break;
      directory = dirname(directory);
    }
    return result;
  }
  function hasHoistedBinary(name) {
    if (!hoisted) {
      const config = manifest(root)?.data?.workspaces;
      const patterns = Array.isArray(config) ? config : config?.packages;
      const lockfile = Array.isArray(patterns) ? read(resolve(root, 'yarn.lock')) : undefined;
      hoisted = [];
      if (lockfile?.startsWith('# THIS IS AN AUTOGENERATED FILE.') && lockfile.includes('# yarn lockfile v1')) {
        for (const pattern of patterns) {
          if (typeof pattern !== 'string' || !/^[\w./*-]+$/.test(pattern) || pattern.includes('**')) continue;
          const parts = pattern.replace(/^\.\//, '').split('/').filter(Boolean);
          for (const directory of workspaceDirectories(root, parts)) {
            const pkg = manifest(directory);
            if (pkg) hoisted.push(pkg);
          }
        }
      }
    }
    return hasLocalBinary(hoisted, name);
  }
  function workspaceDirectories(directory, [part, ...rest]) {
    if (!contains(directory) || part === '..') return [];
    if (!part) return [directory];
    if (!part.includes('*')) return workspaceDirectories(resolve(directory, part), rest);
    const pattern = new RegExp('^' + part.replaceAll('.', '\\.').replaceAll('*', '.*') + '$');
    try {
      if (!contains(realpathSync(directory))) return [];
      return readdirSync(directory, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && pattern.test(entry.name))
        .flatMap((entry) => workspaceDirectories(resolve(directory, entry.name), rest));
    } catch (error) {
      if (error.code === 'ENOENT' || error.code === 'ENOTDIR') return [];
      throw error;
    }
  }
  return {
    root,
    label,
    read,
    packageChain,
    hasHoistedBinary,
    workingDirectory(value, base = root) {
      if (!base || typeof value !== 'string') return undefined;
      const normalized = value.replace(/^(?:\$\{GITHUB_WORKSPACE\}|\$GITHUB_WORKSPACE)(?=\/|$)/, root);
      if (/[$*?~"'\\]/.test(normalized)) return undefined;
      const directory = resolve(base, normalized);
      return contains(directory) ? directory : undefined;
    },
  };
}

export function hasLocalBinary(packages, name) {
  const candidates = [name, ...(Object.hasOwn(binaryProviders, name) ? binaryProviders[name] : [])];
  return packages.some(({ data }) =>
    ['dependencies', 'devDependencies', 'optionalDependencies'].some((kind) =>
      candidates.some((candidate) => Object.hasOwn(data?.[kind] ?? {}, candidate))));
}
